/// `pf` 命令行工具的退出码契约。
///
/// **这三个值是接口的一部分**，脚本与 CI 靠它们区分三种处境，不能随手改动：
///
/// | 码 | 含义 | 调用方该做什么 |
/// |---|---|---|
/// | 0 | 成功，且结论为「是」 | 继续 |
/// | 1 | 结论为「否」 | 这是**业务结论**：文件坏了/密码错/载荷违规。换文件或换密码，别去修工具 |
/// | 2 | 用法错误或基础设施不可用 | 这是**工具故障**：参数不对、文件读不到、环境缺依赖、分支未实现 |
///
/// 为什么必须把 1 与 2 分开（而不是「非零即失败」）：
/// 端到端验收（导出 → 删库 → 导入 → 比对）里，脚本需要判断的是
/// 「这次比对不一致」还是「我这条命令根本没跑起来」。
/// 把两者混成一个非零码，最坏的结果是**基础设施故障伪装成业务结论**——
/// 一次 `verify` 因为文件路径写错返回非零，被解读成「备份文件损坏」。
library;

/// 退出码常量。
abstract final class ExitCodes {
  /// 成功，且结论为「是」。
  static const int ok = 0;

  /// 结论为「否」：文件读得懂，但内容不成立。
  static const int negative = 1;

  /// 用法错误或基础设施不可用。CI 必须把它当成故障，而不是「检查不通过」。
  static const int toolError = 2;
}
